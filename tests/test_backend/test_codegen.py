class TestAssignmentGeneration:
    """Test assignment statement generation."""

    def test_simple_assignment(self) -> None:
        """Test simple assignment."""
        generator = RustCodeGenerator()
        target = IdentifierNode(name="X", line=1, column=1)
        value = LiteralNode(value=5, literal_type="INTEGER", line=1, column=1)
        assign = AssignmentNode(target=target, value=value, line=1, column=1)
        
        program = ProgramNode(name="Test", statements=[assign])
        code = generator.generate(program)
        
        assert "x = 5;" in code

    def test_expression_assignment(self) -> None:
        """Test assignment with expression."""
        generator = RustCodeGenerator()
        target = IdentifierNode(name="RESULT", line=1, column=1)
        
        # Value: X + Y
        left = IdentifierNode(name="X", line=1, column=1)
        right = IdentifierNode(name="Y", line=1, column=1)
        binop = BinaryOpNode(operator="+", left=left, right=right, line=1, column=1)
        
        assign = AssignmentNode(target=target, value=binop, line=1, column=1)
        program = ProgramNode(name="Test", statements=[assign])
        code = generator.generate(program)
        
        assert "result = (x + y);" in code


