class TestFileOperations:
    """Test file writing operations."""

    def test_write_to_file(self) -> None:
        """Test writing generated code to file."""
        generator = RustCodeGenerator()
        program = ProgramNode(name="Test")
        code = generator.generate(program)
        
        # Create temporary file
        with tempfile.NamedTemporaryFile(mode='w', suffix='.rs', delete=False) as f:
            temp_file = f.name
        
        try:
            generator.write_to_file(temp_file, code)
            
            # Verify file was created and contains code
            assert os.path.exists(temp_file)
            
            with open(temp_file, 'r') as f:
                content = f.read()
            
            assert "fn main()" in content
        finally:
            os.unlink(temp_file)


class TestCompleteProgram:
    """Test generating complete programs."""

    def test_complete_hal_program(self) -> None:
        """Test generating a complete HAL/S program."""
        generator = RustCodeGenerator()
        
        # PROGRAM Test;
        #   DECLARE X INTEGER;
        #   X = 5;
        # CLOSE Test;
        
        type_spec = TypeSpec(data_type=DataType.INTEGER)
        decl = DeclareNode(identifiers=["X"], type_spec=type_spec)
        
        target = IdentifierNode(name="X", line=2, column=1)
        value = LiteralNode(value=5, literal_type="INTEGER", line=2, column=5)
        assign = AssignmentNode(target=target, value=value, line=2, column=1)
        
        program = ProgramNode(
            name="Test",
            declarations=[decl],
            statements=[assign],
            procedures=[]
        )
        
        code = generator.generate(program)
        
        # Verify structure
        assert "fn main()" in code
        assert "let mut x: i32;" in code
        assert "x = 5;" in code
        assert "// HAL/S Program: Test" in code
